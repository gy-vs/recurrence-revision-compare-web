interface StreamResult {
  events: {id: number; event: string; data: any}[];
  done: Promise<void>;
}

function openStream(app: ReturnType<typeof createApp>, url: string, lastEventId?: number): StreamResult {
  const events: StreamResult['events'] = [];
  const req = request(app).get(url).buffer(true).parse((res, cb) => {
    let buffer = '';
    res.on('data', chunk => {
      buffer += chunk.toString();
      let sep: number;
      while ((sep = buffer.indexOf('\n\n')) >= 0) {
        const raw = buffer.slice(0, sep);
        buffer = buffer.slice(sep + 2);
        let id = 0;
        let event = 'message';
        const dataLines: string[] = [];
        for (const line of raw.split('\n')) {
          if (line.startsWith('id:')) id = Number(line.slice(3).trim());
          else if (line.startsWith('event:')) event = line.slice(6).trim();
          else if (line.startsWith('data:')) dataLines.push(line.slice(5).trim());
        }
        if (event === 'ping' || raw.startsWith(':')) continue;
        events.push({id, event, data: JSON.parse(dataLines.join(''))});
      }
    });
    res.on('end', () => cb(null, Buffer.alloc(0)));
    res.on('error', cb);
  });
  if (lastEventId !== undefined) req.set('Last-Event-ID', String(lastEventId));
  const done = req.then(() => undefined);
  return {events, done};
}

describe('compare HTTP API', () => {
  it('pins both revisions in a session and streams complete ordered results', async () => {
    const app = createApp();
    const created = await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 1, newRevision: 2, from: '2026-01-01', to: '2026-01-31'})
      .expect(201);
    expect(created.body.oldRevision).toBe(1);
    expect(created.body.newRevision).toBe(2);

    const stream = openStream(app, created.body.streamUrl);
    await stream.done;

    const names = stream.events.map(e => e.event);
    expect(names[0]).toBe('start');
    expect(names[names.length - 1]).toBe('done');
    expect(stream.events.filter(e => e.event === 'item').length).toBeGreaterThan(0);

    const done = stream.events.find(e => e.event === 'done')!.data;
    expect(done.complete).toBe(true);
    expect(done.stats.added + done.stats.removed).toBe(0);
    expect(done.stats.modified).toBeGreaterThan(0);

    // Event ids are sequential and item keys are in stable order.
    const ids = stream.events.map(e => e.id);
    expect(ids).toEqual(ids.map((_, i) => i + 1));
    const instants = stream.events.filter(e => e.event === 'item').map(e =>
      e.data.old?.instant ?? e.data.next.instant);
    expect(instants).toEqual([...instants].sort());

    // Seeded orphan: r3 stand-up interval 2, cancel targets 2026-02-09.
    const orphanSession = await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 1, newRevision: 3, from: '2026-02-01', to: '2026-02-28'})
      .expect(201);
    const orphanStream = openStream(app, orphanSession.body.streamUrl);
    await orphanStream.done;
    const ex = orphanStream.events.find(e => e.event === 'exception' && e.data.id === 'cancel-holiday')!.data;
    expect(ex.status).toBe('orphaned');
    expect(ex.next.resolved).toBe(false);
  });

  it('resumes with Last-Event-ID and replays only missed events', async () => {
    const app = createApp();
    const created = await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 1, newRevision: 2, from: '2026-01-01', to: '2026-01-15'})
      .expect(201);
    const first = openStream(app, created.body.streamUrl);
    await first.done;
    const resumeAfter = first.events[2].id;
    const resumed = openStream(app, created.body.streamUrl, resumeAfter);
    await resumed.done;
    expect(resumed.events.length).toBe(first.events.length - resumeAfter);
    expect(resumed.events[0].id).toBe(resumeAfter + 1);
  });

  it('rejects unknown revisions and invalid windows', async () => {
    const app = createApp();
    await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 1, newRevision: 99, from: '2026-01-01', to: '2026-01-31'})
      .expect(400);
    await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 2, newRevision: 1, from: '2026-03-01', to: '2026-01-01'})
      .expect(400);
    await request(app).get('/api/compare/nope/stream').expect(404);
  });

  it('does not let later saves mutate a pinned session', async () => {
    const app = createApp();
    const head = await request(app).get('/api/schedules/alpha').expect(200);
    // Pin r2 (Chicago) -> r4 (NY segmented); wall-clock times identical.
    const created = await request(app).post('/api/schedules/alpha/compare')
      .send({oldRevision: 2, newRevision: head.body.revision, from: '2026-01-01', to: '2026-01-10'})
      .expect(201);
    const doc = JSON.parse(head.body.content);
    doc.segments[0].localTime = '04:00';
    await request(app).put('/api/schedules/alpha')
      .send({doc, revision: head.body.revision, note: 'later edit'})
      .expect(200);
    const stream = openStream(app, created.body.streamUrl);
    await stream.done;
    const done = stream.events.find(e => e.event === 'done')!.data;
    expect(done.complete).toBe(true);
    // Session is pinned to the saved r4, which never contains 04:00.
    const items = stream.events.filter(e => e.event === 'item');
    for (const e of items) {
      if (e.data.next) expect(e.data.next.localTime).not.toBe('04:00');
    }
  });
});
